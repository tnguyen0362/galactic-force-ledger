def load_img(fn, srgb):
    p = os.path.join(TEX, fn)
    for im in list(bpy.data.images):
        if im.name == fn:
            bpy.data.images.remove(im)
    im = bpy.data.images.load(p, check_existing=False)
    im.name = fn
    im.colorspace_settings.name = "sRGB" if srgb else "Non-Color"
    im.alpha_mode = "NONE" if hasattr(im, "alpha_mode") else im.alpha_mode
    return im


def make_pbr():
    for nm in ("GF_Hero_PBR", "GF_Hero_Glow"):
        if nm in bpy.data.materials:
            bpy.data.materials.remove(bpy.data.materials[nm])
    m = bpy.data.materials.new("GF_Hero_PBR")
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    N, L = nt.nodes, nt.links
    out = N.new("ShaderNodeOutputMaterial")
    bsdf = N.new("ShaderNodeBsdfPrincipled")
    L.new(bsdf.outputs["BSDF"], out.inputs["Surface"])
    bc = N.new("ShaderNodeTexImage")
    bc.image = load_img("GF_Hero_Asc_BC.png", True)
    nm = N.new("ShaderNodeTexImage")
    nm.image = load_img("GF_Hero_Asc_N.png", False)
    rm = N.new("ShaderNodeTexImage")
    rm.image = load_img("GF_Hero_Asc_RM.png", False)
    for t in (bc, nm, rm):
        t.interpolation = "Linear"
        t.extension = "REPEAT"
    nmap = N.new("ShaderNodeNormalMap")
    sep = N.new("ShaderNodeSeparateColor")
    L.new(bc.outputs["Color"], bsdf.inputs["Base Color"])
    L.new(nm.outputs["Color"], nmap.inputs["Color"])
    L.new(nmap.outputs["Normal"], bsdf.inputs["Normal"])
    L.new(rm.outputs["Color"], sep.inputs["Color"])
    L.new(sep.outputs["Green"], bsdf.inputs["Roughness"])
    L.new(sep.outputs["Blue"], bsdf.inputs["Metallic"])
    g = bpy.data.materials.new("GF_Hero_Glow")
    g.use_nodes = True
    gb = next(n for n in g.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
    gb.inputs["Base Color"].default_value = (0.40, 0.12, 0.80, 1)
    gb.inputs["Emission Color"].default_value = (0.55, 0.20, 1.0, 1)
    gb.inputs["Emission Strength"].default_value = 4.0
    return m, g


def collapse():
    pbr, glow = make_pbr()
    for n, o in objs.items():
        o.data.materials.clear()
        o.data.materials.append(glow if n.startswith("Glow_") else pbr)
        for p in o.data.polygons:
            p.material_index = 0
    return pbr, glow


