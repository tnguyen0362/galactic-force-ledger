# ------------------------------------------------------------------ export
RBX = {"LeftUpperArm": "UpperArmL", "LeftLowerArm": "LowerArmL", "LeftHand": "HandL", "RightUpperArm": "UpperArmR",
       "RightLowerArm": "LowerArmR", "RightHand": "HandR", "LeftUpperLeg": "UpperLegL", "LeftLowerLeg": "LowerLegL",
       "LeftFoot": "FootL", "RightUpperLeg": "UpperLegR", "RightLowerLeg": "LowerLegR", "RightFoot": "FootR"}


def rbx_pt(v):  # blender (authoring, studs) -> roblox/glTF frame
    return Vector((v.x, v.z, -v.y))


def export(J, PARENT):
    # scale to studs
    for o in objs.values():
        o.data.transform(Matrix.Scale(S, 4))
        o.data.update()
    parts = {}
    dg = bpy.context.evaluated_depsgraph_get()
    for n, o in objs.items():
        me = o.data
        pts = [rbx_pt(v.co) for v in me.vertices]
        lo = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
        hi = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
        tris = sum(len(p.vertices) - 2 for p in me.polygons)
        parts[RBX.get(n, n)] = dict(center=(lo + hi) / 2, size=hi - lo, tris=tris, nverts=len(me.vertices))
    # pivots
    piv = {}
    for bn, par in PARENT.items():
        if bn == "Rifle":
            continue
        rn = RBX.get(bn, bn)
        piv[rn] = dict(head=rbx_pt(J[bn] * S), parent=RBX.get(par, par) if par else None)
    piv["Rifle"] = dict(head=rbx_pt(J["Rifle"] * S), parent="HandR")

    def vf(v):
        return "Vector3.new(%.4f, %.4f, %.4f)" % (v.x, v.y, v.z)

    L = ["-- GENERATED by gf-art-build/blender/hero_export.py (v8 anatomical rifleman). Studs, feet at y=0, model faces -Z, right-handed shooter.",
         "return {", "\tparts = {"]
    for rn, d in parts.items():
        L.append('\t\t["%s"] = { center = %s, size = %s, tris = %d },' % (rn, vf(d["center"]), vf(d["size"]), d["tris"]))
    L.append("\t},")
    L.append("\tpivots = {")
    for rn, d in piv.items():
        L.append('\t\t["%s"] = { head = %s, parent = %s },' % (rn, vf(d["head"]), ('"%s"' % d["parent"]) if d["parent"] else "nil"))
    L.append("\t},")
    L.append("}")
    open(LUA, "w", encoding="utf-8").write("\n".join(L) + "\n")
    # glb
    bpy.ops.object.select_all(action="DESELECT")
    for o in objs.values():
        o.hide_set(False)
        o.select_set(True)
    bpy.context.view_layer.objects.active = list(objs.values())[0]
    bpy.ops.export_scene.gltf(filepath=GLB, export_format="GLB", use_selection=True, export_apply=True, export_yup=True,
                              export_texcoords=True, export_normals=True, export_materials="EXPORT", export_cameras=False,
                              export_lights=False)
    tot = sum(d["tris"] for d in parts.values())
    print("exported", GLB, os.path.getsize(GLB), "bytes; tris", tot)
    ymin = min(d["center"].y - d["size"].y / 2 for d in parts.values())
    ymax = max(d["center"].y + d["size"].y / 2 for d in parts.values())
    print("height studs", round(ymax - ymin, 3), "ymin", round(ymin, 3))
    return parts, piv
