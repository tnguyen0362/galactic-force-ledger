"""Export PLAYERKIT -> GLB + Luau data (limb-local bbox centres in the Roblox frame). Run inside Blender after gen_player_kit.py."""
import bpy, os
from mathutils import Vector

# Set GF_REPO (repo root) and GF_ART_OUT (GLB output dir) before running; defaults assume ~/galactic-force.
REPO = os.environ.get("GF_REPO", os.path.join(os.path.expanduser("~"), "galactic-force"))
OUTD = os.environ.get("GF_ART_OUT", os.path.join(os.path.expanduser("~"), "gf-art-build", "blender", "out_player"))
GLB = os.path.join(OUTD, "Player_SEAL_Kit_v1.glb")
LUA = os.path.join(REPO, "tools", "art", "player", "player_kit_data.luau")
os.makedirs(OUTD, exist_ok=True)

exec(open(os.path.join(REPO, "tools", "art", "player", "blender", "gen_player_kit.py"), encoding="utf-8").read(), {"__name__": "gen"}) if "PLAYERKIT" not in bpy.data.collections else None
DIMS = {"Head": (1.2, 1.2, 1.2), "UpperTorso": (2.0, 1.0, 1.6), "LowerTorso": (2.0, 1.0, 0.4), "UpperArm": (1.0, 1.0, 1.2),
        "LowerArm": (1.0, 1.0, 1.1), "Hand": (1.0, 1.0, 0.3), "UpperLeg": (1.0, 1.0, 1.2), "LowerLeg": (1.0, 1.0, 1.2), "Foot": (1.0, 1.0, 0.3)}


def rbx(v):  # authoring (x right, y front, z up) -> roblox/glTF (x, y up, z back)
    return Vector((v.x, v.z, -v.y))


coll = bpy.data.collections["PLAYERKIT"]
lc = bpy.context.view_layer.layer_collection.children["PLAYERKIT"]
lc.exclude = False
objs = [o for o in coll.objects if o.type == "MESH"]
rows = []
tot = 0
for o in sorted(objs, key=lambda o: o.name):
    pts = [rbx(v.co) for v in o.data.vertices]
    lo = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    hi = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    tris = len(o.data.polygons)
    tot += tris
    rows.append((o.name, o["limb"], o["side"], o["group"], (lo + hi) / 2, hi - lo, tris))


def vf(v):
    return "Vector3.new(%.4f, %.4f, %.4f)" % (v.x, v.y, v.z)


L = ["-- GENERATED by tools/art/player/blender/export_player_kit.py. Limb-local frame (Roblox axes, origin = limb centre at reference scale).",
     "-- center/size are the mesh bbox in that frame; refDims are the reference R15 limb sizes the kit was authored against.",
     "return {", "\trefDims = {"]
for k, d in DIMS.items():
    L.append('\t\t%s = Vector3.new(%.3f, %.3f, %.3f),' % (k, d[0], d[2], d[1]))  # (x, up, depth)
L.append("\t},")
L.append("\tparts = {")
for name, limb, side, grp, c, s, t in rows:
    L.append('\t\t["%s"] = { limb = "%s", side = "%s", group = "%s", center = %s, size = %s, tris = %d },' % (name, limb, side, grp, vf(c), vf(s), t))
L.append("\t},")
L.append("}")
open(LUA, "w", encoding="utf-8").write("\n".join(L) + "\n")
bpy.ops.object.select_all(action="DESELECT")
for o in objs:
    o.hide_set(False)
    o.select_set(True)
bpy.context.view_layer.objects.active = objs[0]
bpy.ops.export_scene.gltf(filepath=GLB, export_format="GLB", use_selection=True, export_apply=True, export_yup=True,
                          export_materials="EXPORT", export_cameras=False, export_lights=False, export_texcoords=False)
lc.exclude = True
print("exported", GLB, os.path.getsize(GLB), "bytes;", len(objs), "meshes;", tot, "tris")
